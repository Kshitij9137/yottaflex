"""Render docs/validation_summary.md (deterministic: no timestamps or paths)."""
from __future__ import annotations

from collections import defaultdict

GENERATED = ("SCH-", "KEY-PK-", "FK:", "DUP-ROW:", "DUP-NATURAL:")
ORDER = ["Schema", "Keys", "Duplicates", "Foreign keys", "Cardinality", "Conditional rules", "Dates",
         "Temporal availability", "Reconciliation", "Lifecycle"]


def _tbl(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def _by_category(results, base_results):
    cat = defaultdict(lambda: {"rules": 0, "fail_data": 0, "fail_base": 0, "rows": 0})
    base = {r.rule_id: r for r in base_results} if base_results else {}
    for r in results:
        c = cat[r.category]
        c["rules"] += 1
        c["fail_data"] += int(r.n_violations > 0)
        c["fail_base"] += int(r.rule_id in base and base[r.rule_id].n_violations > 0)
        c["rows"] = max(c["rows"], r.n_checked)
    return cat


def render(meta: dict | None, results, ev: dict, base_results, verdict: bool, custom_rule_docs) -> str:
    L = ["# Validation Summary", "",
         "Generated by `python -m yottaflex.validate --data data/full --report docs/validation_summary.md`. "
         "The validator reads the **exported CSV files** (not in-memory objects), so what is checked is what a reviewer receives.", ""]
    if meta:
        rc = meta["row_counts"]
        L += ["## 1. Dataset validated", "",
              f"- Seed `{meta['seed']}`, `{meta['n_employees']:,}` employees, generator command: `{meta['generator_command'].replace('<dir>', 'data/full')}`",
              f"- Voluntary attrition {meta['voluntary_attrition_rate']:.2%}, involuntary {meta['involuntary_attrition_rate']:.2%} (documented bound: 5-15% total)",
              "- Row counts: " + ", ".join(f"{k} {v:,}" for k, v in rc.items()), ""]
    L += ["## 2. Verdict", ""]
    rows = []
    if base_results is not None:
        nb = sum(r.n_violations > 0 for r in base_results)
        rows.append(["Clean baseline (same seed, no injection): rules with violations", nb, "PASS" if nb == 0 else "FAIL"])
    if ev.get("has_ground_truth"):
        rows += [["Injected dataset: violating records not explained by the ground truth", ev["unexplained_violations"], "PASS" if ev["unexplained_violations"] == 0 else "FAIL"],
                 ["Injected records that no rule flags", ev["injected_records_not_flagged_by_any_rule"], "PASS" if ev["injected_records_not_flagged_by_any_rule"] == 0 else "FAIL"],
                 ["Benign decoys flagged by any rule", f"{ev['decoys_flagged_by_any_rule']} of {ev['decoys_total']}", "PASS" if ev["decoys_flagged_by_any_rule"] == 0 else "FAIL"],
                 ["Ground-truth records missing from the tables", ev["gt_records_missing_from_tables"], "PASS" if ev["gt_records_missing_from_tables"] == 0 else "FAIL"],
                 ["Detectors with precision and recall of 1.00", f"{sum(d['precision'] == 1 and d['recall'] == 1 for d in ev['detectors'])} of {len(ev['detectors'])}",
                  "PASS" if all(d['precision'] == 1 and d['recall'] == 1 for d in ev['detectors']) else "FAIL"]]
    else:
        rows.append(["Rules with violations on the validated data", len(ev["rules_with_violations"]), "PASS" if not ev["rules_with_violations"] else "FAIL"])
    L += [_tbl(["Check", "Result", "Status"], rows), "", f"**Overall: {'PASS' if verdict else 'FAIL'}**", ""]

    L += ["## 3. What was checked (Step 8)", "",
          f"{ev['n_rules']} rules in 10 categories. Most schema, key and foreign-key rules are generated from the machine-readable data dictionary "
          "(`validate/schema.py`), so the dictionary and the checks cannot drift apart. The last two columns count how many rules in each category fired.", ""]
    cat = _by_category(results, base_results)
    hdr = ["Category", "Rules", "Max rows checked", "Rules firing: baseline", "Rules firing: injected data"]
    L += [_tbl(hdr, [[k, cat[k]["rules"], f"{cat[k]['rows']:,}", cat[k]["fail_base"] if base_results is not None else "n/a", cat[k]["fail_data"]]
                     for k in ORDER if k in cat]), ""]
    L += ["Requirement coverage: primary-key uniqueness and format (`KEY-PK-*`), foreign-key integrity (`FK:*`, `CARD-*`), allowed enums and ranges (`SCH-ENUM`, `SCH-RANGE`), "
          "date ordering (`DATE-*`, `TIME-*`), arithmetic reconciliation (`RECON-*`), lifecycle transitions (`LIFE-*`), duplicates (`DUP-*`).", ""]

    if ev.get("has_ground_truth"):
        L += ["## 4. Anomaly detectors scored against the ground truth", "",
              "A detector is a named set of rules (tagged `maps_to`). It never reads the ground truth; the ground truth is only used afterwards to score it.", ""]
        L += [_tbl(["Issue type", "Detector rules", "Injected", "Flagged", "TP", "FP", "FN", "Precision", "Recall", "F1"],
                   [[d["issue_type"], "<br>".join(f"`{r}`" for r in d["rules"]), d["truth"], d["flagged"], d["tp"], d["fp"], d["fn"],
                     f"{d['precision']:.2f}", f"{d['recall']:.2f}", f"{d['f1']:.2f}"] for d in ev["detectors"]]), ""]
        L += ["Recall by subtype:", "", _tbl(["Issue type", "Subtype", "Injected", "Found", "Recall"],
                                            [[s["issue_type"], s["issue_subtype"], s["truth"], s["found"], f"{s['recall']:.2f}"] for s in ev["subtypes"]]), ""]
        L += ["## 5. Benign decoys: why they exist", "",
              f"{ev['decoys_total']} untouched rows look suspicious but are normal. Our rules flag **{ev['decoys_flagged_by_any_rule']}** of them. "
              "A tempting shortcut rule would flag all of them:", "",
              _tbl(["Naive rule", "Flags in the dataset", "Decoys of its type", "Decoys wrongly flagged", "Our detectors"],
                   [[n["rule"], f"{n['flags_in_dataset']:,}", n["decoys"], f"{n['decoys_wrongly_flagged']} ({n['share_of_decoys_wrongly_flagged']:.0%})",
                     n["our_detectors_flag_these_decoys"]] for n in ev["naive_rules"]]), ""]
        fired = [r for r in results if r.n_violations]
        L += ["## 6. Every violation in the injected data, and why", "",
              f"{ev['violating_records_total']:,} records are flagged by at least one rule; {ev['violating_records_explained']:,} are injected ground-truth records "
              f"and **{ev['unexplained_violations']}** are unexplained. Several rules can fire on one injected record "
              "(for example a post-exit snapshot also fails the team-coverage check), so counts below can exceed the injected totals.", "",
              _tbl(["Rule", "Entity", "Records flagged", "Not explained by GT", "Role"],
                   [[f"`{r.rule_id}`", r.entity, r.n_violations, ev["unexplained_violations_by_rule"].get(r.rule_id, 0),
                     f"detector for `{r.maps_to}`" if r.maps_to else "collateral signal"] for r in fired]), ""]
    L += ["## 7. Hand-written rule catalogue", "",
          "Generated rules (`SCH-*`, `KEY-PK-*`, `FK:*`, `DUP-ROW:*`, `DUP-NATURAL:*`) are per table or column. The rest:", "",
          _tbl(["Rule", "Category", "What it asserts"], [[f"`{r.rule_id}`", r.category, r.description] for r in custom_rule_docs]), ""]
    L += ["## 8. Limits of this validation", "",
          "- **Perfect detector scores are expected, not impressive.** The anomalies are deterministic signatures, so a rule that matches the signature finds them all. "
          "What the result does show: the ground truth is correct, the injection touched only labelled records, no decoy is flagged, and the clean baseline passes every rule. "
          "A real system would see fuzzier anomalies and trade precision against recall.",
          "- **Shared helpers.** The validator reuses `dates.months_between` and `labels.derive_label` from the generator, so a bug inside those two functions would not be caught here. "
          "Every other derived value is recomputed with independent code.",
          "- **No natural key for Employee.** The table carries no personal attributes by design, so duplicate detection relies on primary-key uniqueness (`DUP-ROW` is not applied to it).",
          "- **Leak detection is timestamp-based.** It catches rows recorded after their own snapshot day and rows dated after exit. A leak with a falsified `recorded_at` would need lineage checks outside this dataset.",
          "- **Bounds-based salary check.** Merit is not stored as its own event, so salary steps are validated against allowed ranges, not exact amounts.", ""]
    return "\n".join(L)